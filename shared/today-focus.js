import { unreadFamilyCount } from "./session-read.js";
import { familyRoots } from "./today-layout.js";

// Persistent archive preferences are shown only when they affect this snapshot.
export function relevantArchives(sessions, hidden = []) {
  const ids = new Set(sessions.map((s) => s.id));
  const streams = new Set(sessions.map((s) => String(s.boardStreamId)));
  return hidden.filter((h) =>
    h.kind === "session" ? ids.has(h.id) : streams.has(String(h.id)),
  );
}

export function openTaskStreamIds(tasks) {
  return new Set(
    tasks.filter((t) => t.status !== "done").map((t) => t.streamId),
  );
}

/**
 * @param {{ suspended?: boolean, created: string, id: string }} a
 * @param {{ suspended?: boolean, created: string, id: string }} b
 */
export function compareTasks(a, b) {
  return (
    Number(!!a.suspended) - Number(!!b.suspended) ||
    Date.parse(b.created) - Date.parse(a.created) ||
    b.id.localeCompare(a.id)
  );
}

export function focusedSessions(sessions, edges, hidden = []) {
  const dismissed = new Set(
    hidden.filter((h) => h.kind === "session").map((h) => h.id),
  );
  const streams = new Set(
    hidden.filter((h) => h.kind === "stream").map((h) => String(h.id)),
  );
  const forest = familyRoots(sessions, edges);
  return sessions.filter((s) => {
    if (streams.has(String(s.boardStreamId))) return false;
    let id = s.id;
    const seen = new Set();
    while (id && !seen.has(id)) {
      if (dismissed.has(id)) return false;
      seen.add(id);
      id = forest.parent.get(id);
    }
    return true;
  });
}

// Count separate half-hour periods of human work, rather than the number of
// subagents, copied histories, tool calls or paragraphs generated by an agent.
export function streamActivity(sessions, start, end) {
  const groups = new Map();
  for (const s of sessions) {
    if (
      s.boardStreamId == null ||
      (s.child && s.relationship !== "shared_history")
    )
      continue;
    if (!groups.has(s.boardStreamId)) groups.set(s.boardStreamId, new Map());
    const requests = groups.get(s.boardStreamId);
    for (const r of s.activity || []) {
      const at = Date.parse(r.at);
      if (at >= start && at < end) requests.set(r.id, at);
    }
  }
  return new Map(
    [...groups].map(([id, requests]) => {
      const times = [...requests.values()];
      return [
        id,
        {
          periods: new Set(
            times.map((at) => Math.floor((at - start) / 1800000)),
          ).size,
          requests: times.length,
          latest: Math.max(0, ...times),
        },
      ];
    }),
  );
}
export function compareStreamActivity(a, b) {
  return (
    (b.activity?.periods || 0) - (a.activity?.periods || 0) ||
    (b.activity?.requests || 0) - (a.activity?.requests || 0) ||
    (b.activity?.latest || 0) - (a.activity?.latest || 0) ||
    (a.name || "").localeCompare(b.name || "")
  );
}

// Status badges describe the same unarchived sessions as the Today cards.
export function todayStatusCounts(sessions, edges, hidden = []) {
  const current = focusedSessions(sessions, edges, hidden);
  return {
    all: current.length,
    running: current.filter((s) => s.status === "running").length,
    unread: unreadFamilyCount(current, edges),
  };
}
